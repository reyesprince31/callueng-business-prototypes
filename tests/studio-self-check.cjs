const assert=require('node:assert/strict');
const {defaultDirection,validateDirection,directionText,conceptPrompts,assistantReply,validateMeeting,meetingHTML,validateProject,validateBrief,sampleAllowance,briefText,validateSupport,supportText}=require('../site.js');
const d={...defaultDirection(),previewStyle:'tropical',exteriorStyle:'tropical',interiorStyle:'japandi',exteriorIdeas:['Garden entrance','Garden entrance'],interiorIdeas:['Natural light'],note:'<script>alert(1)</script>',chatNotes:['I would like more storage.']};
assert.deepEqual(validateDirection(d).exteriorIdeas,['Garden entrance']);
assert.ok(directionText(d).includes('Preferred interior: Japandi'));
for(const key of ['style','palette','previewStyle','exteriorStyle','interiorStyle'])assert.throws(()=>validateDirection({...d,[key]:'__proto__'}));
assert.throws(()=>validateDirection({...d,style:['tropical']}));
assert.throws(()=>validateDirection({...d,palette:['warm']}));
assert.throws(()=>validateDirection({...d,exteriorIdeas:['Unknown']}));
assert.throws(()=>validateDirection({...d,note:'x'.repeat(601)}));
assert.throws(()=>validateDirection({...d,chatNotes:Array(7).fill('Question')}));
assert.throws(()=>validateDirection(null));
assert.equal(assistantReply('I want a calm Japandi home',d).style,'japandi');
assert.equal(assistantReply('I like minimal and classic',d).style,undefined);
assert.equal(assistantReply('How much will it cost?',d).href,'plan.html');
assert.equal(assistantReply('Can I get blueprint services?',d).href,'blueprinting.html#print-request');
assert.equal(assistantReply('I want blueprint printing',d).href,'blueprinting.html#print-request');
assert.equal(assistantReply('I need a hauling service',d).href,'site-support.html');
assert.equal(assistantReply('Can you check a structural beam?',d).href,'team.html');
assert.throws(()=>assistantReply(' ',d));
assert.throws(()=>assistantReply('x'.repeat(601),d));
assert.equal(assistantReply('How much for blueprint printing?',d).href,'blueprinting.html#print-request');
assert.equal(assistantReply('I need architectural plans',d).href,'plan.html?service=Blueprint%20%2F%20plan%20set%20only');
const project=validateProject({type:'Residence',city:'Antipolo',area:'120'});
const meeting=validateMeeting({kind:'Design consultation',date:'2026-10-20'},'2026-10-14');
for(const date of ['2026-10-13','2026-02-30','invalid','2026-13-01'])assert.throws(()=>validateMeeting({kind:'Design consultation',date},'2026-10-14'));
assert.equal(validateMeeting({kind:'Blueprint / plan consultation',date:''},'2026-10-14').date,'');
const html=meetingHTML(project,d,meeting,{exterior:'data:image/webp;base64,AA==',interior:'data:image/webp;base64,AA=='});
assert.ok(html.includes('&lt;script&gt;alert(1)&lt;/script&gt;'));
assert.ok(!html.includes('<script>'));
assert.ok(html.includes('Modern tropical')&&html.includes('Japandi'));
assert.throws(()=>meetingHTML(project,{...d,interiorStyle:null},meeting,{exterior:'data:image/webp;base64,AA==',interior:'data:image/webp;base64,AA=='}));
assert.throws(()=>meetingHTML(project,d,meeting,{exterior:'https://example.com/image',interior:'data:image/webp;base64,AA=='}));
assert.ok(conceptPrompts(project,d).includes('Garden entrance'));
const brief=validateBrief({...project,service:'Blueprint / plan set only',site:'To confirm',finish:'Help me decide',budget:'Discuss with the team',timing:'Still exploring',drawings:'Not yet',priorities:[],notes:''});
assert.throws(()=>sampleAllowance(brief));
assert.throws(()=>sampleAllowance({...brief,service:'Blueprint printing / plan copies'}));
assert.ok(briefText({...brief,direction:d}).includes('DESIGN DIRECTION'));
assert.throws(()=>validateBrief({...brief,service:'Unknown'}));
const request=validateSupport({kinds:['materials','hauling'],city:'Antipolo',note:'Cement bags and material delivery for discussion.',date:'2026-10-20'},'2026-10-14');
assert.ok(supportText(request).includes('Hardware & materials, Hauling & delivery'));
for(const kinds of [[],['unknown'],['__proto__']])assert.throws(()=>validateSupport({...request,kinds},'2026-10-14'));
assert.throws(()=>validateSupport({...request,kinds:[['materials']]},'2026-10-14'));
assert.throws(()=>validateSupport({...request,note:'short'},'2026-10-14'));
assert.throws(()=>validateSupport({...request,date:'2026-10-13'},'2026-10-14'));
console.log('PASS: direction validation, mixed preferences, assistant routing, calendar dates, HTML escaping, embedded images, plans-only scope, and site-support requests.');
