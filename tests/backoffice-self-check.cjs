const assert = require('node:assert/strict');
const {seedOffice,workspace,getRecord,validateRecord,saveRecord,saveCopy,validDate,escapeHTML} = require('../backoffice.js');
const state=seedOffice();
assert.throws(()=>workspace(state,'__proto__'));
assert.throws(()=>getRecord(state,'printing','passwords','id'));
const before=JSON.stringify(workspace(state,'printing'));
const id=saveRecord(state,'construction','contacts','',{name:'Demo contact',email:'test@example.com',phone:'',company:'',notes:'<script>alert(1)</script>'});
assert.equal(getRecord(state,'construction','contacts',id).name,'Demo contact');
assert.equal(JSON.stringify(workspace(state,'printing')),before);
assert.throws(()=>getRecord(state,'printing','contacts',id));
assert.throws(()=>saveRecord(state,'printing','contacts',id,{name:'Other',email:'',phone:'',company:'',notes:''}));
assert.throws(()=>validateRecord(state,'printing','leads',{title:'Cross-business',contactId:id,stage:'New',source:'Website form',details:''}));
const leadId=saveRecord(state,'construction','leads','',{title:'Linked enquiry',contactId:id,stage:'New',source:'Website form',details:'Discuss the brief'});
assert.equal(getRecord(state,'construction','leads',leadId).contactId,id);
assert.throws(()=>validateRecord(state,'construction','contacts',{name:'',email:'wrong',phone:'',company:'',notes:''}));
assert.throws(()=>validateRecord(state,'construction','contacts',{name:'A',email:'wrong',phone:'',company:'',notes:''}));
assert.throws(()=>validateRecord(state,'construction','leads',{title:'A',contactId:'',stage:'Anything',source:'Phone',details:''}));
assert.equal(validDate('2026-02-30'),false);assert.equal(validDate('2028-02-29'),true);
const meeting={title:'Discuss demo',contactId:id,date:'2026-10-20',time:'10:30',mode:'Video call',status:'Proposed',notes:''};
assert.throws(()=>validateRecord(state,'construction','meetings',{...meeting,time:'25:00'}));
saveRecord(state,'construction','meetings','',meeting);
const page=getRecord(state,'construction','pages','home'), published={...page.published};
saveCopy(state,'construction','home',{...page.draft,headline:'A new draft'});
assert.equal(page.draft.headline,'A new draft');assert.deepEqual(page.published,published);
assert.throws(()=>saveCopy(state,'construction','home',{...page.draft,headline:''}));
saveCopy(state,'construction','home',page.draft,true);assert.deepEqual(page.published,page.draft);
page.draft.headline='Later edit';assert.equal(page.published.headline,'A new draft');
assert.equal(JSON.stringify(workspace(state,'printing')),before);
assert.equal(escapeHTML('<img src=x onerror="alert(1)">'),'&lt;img src=x onerror=&quot;alert(1)&quot;&gt;');
state.orgs.hardware.contacts=Array.from({length:200},(_,index)=>({id:String(index)}));
assert.throws(()=>saveRecord(state,'hardware','contacts','',{name:'At capacity',email:'',phone:'',company:'',notes:''}));
console.log('PASS: separate business records, contact references, validation, bounded demo data, escaped copy, and draft/publish isolation.');
