const assert = require('node:assert/strict');
const {validateBrief, briefQuestions, sampleAllowance, briefText} = require('../site.js');
const draft = {type:'Residence',city:' Antipolo ',area:'120',site:'To confirm',finish:'Mid-range',budget:'Discuss with the team',timing:'Still exploring',drawings:'Not yet',priorities:['Natural light','Natural light'],notes:' Garden connection '};
const valid = validateBrief(draft);
assert.equal(valid.city, 'Antipolo');
assert.equal(valid.area, 120);
assert.equal(valid.notes, 'Garden connection');
assert.deepEqual(valid.priorities, ['Natural light']);
assert.deepEqual(sampleAllowance(valid), {rate:30000,total:3600000});
for (const area of ['', '19', '2001', '120.5', 'NaN', Infinity, null, [], {}]) assert.throws(() => validateBrief({...draft,area}));
for (const city of [' ', 'A', 'x'.repeat(81), 120]) assert.throws(() => validateBrief({...draft,city}));
for (const key of ['type','site','finish','budget','timing','drawings']) assert.throws(() => validateBrief({...draft,[key]:'__proto__'}));
assert.throws(() => validateBrief({...draft,priorities:['Unknown']}));
assert.throws(() => validateBrief({...draft,notes:'x'.repeat(1001)}));
assert.throws(() => validateBrief(null));
assert.equal(validateBrief({...draft,area:20}).area,20);
assert.equal(validateBrief({...draft,area:2000}).area,2000);
assert.ok(briefQuestions({...valid,type:'Renovation',timing:'Within 3 months',finish:'Help me decide'}).some(q=>q.includes('existing conditions')));
assert.ok(briefText(valid).includes('Nothing has been sent'));
assert.ok(briefText(valid).includes('120 m²'));
assert.ok(briefText(validateBrief({...draft,notes:'<script>alert(1)</script>'})).includes('<script>alert(1)</script>'));
console.log('PASS: validation boundaries, enums, priorities, sample arithmetic, planning prompts, and plain-text export.');
